"""Typed schemas and state definitions for the Cindercrest Agent Brain."""

from datetime import UTC, datetime
from enum import StrEnum
from typing import Any

from pydantic import BaseModel, Field


class TaskIntent(StrEnum):
    """Categorized user intent driving the planning pipeline."""

    CONVERSATION = "CONVERSATION"
    INFORMATION = "INFORMATION"
    TASK_EXECUTION = "TASK_EXECUTION"


class TaskState(StrEnum):
    """Authoritative lifecycle states of an agent task."""

    CREATED = "CREATED"
    PLANNING = "PLANNING"
    AWAITING_APPROVAL = "AWAITING_APPROVAL"
    RUNNING = "RUNNING"
    VERIFYING = "VERIFYING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"
    OUTCOME_UNKNOWN = "OUTCOME_UNKNOWN"


class TaskOutcome(StrEnum):
    """Independent outcome assessment."""

    SUCCESS = "success"
    FAILURE = "failure"
    UNKNOWN = "unknown"
    CANCELLED = "cancelled"


class ToolSafetyTier(StrEnum):
    """Security classification for tool capabilities."""

    READ = "READ"
    WRITE = "WRITE"
    DESTRUCTIVE = "DESTRUCTIVE"


class PolicyDecision(StrEnum):
    """Gatekeeper policy decisions for proposed tool calls."""

    ALLOW = "ALLOW"
    DENY = "DENY"
    REQUIRE_APPROVAL = "REQUIRE_APPROVAL"


class PolicyEvaluationResult(BaseModel):
    """Result of policy evaluation on a proposed action step."""

    decision: PolicyDecision
    reason: str
    tool_name: str
    safety_tier: ToolSafetyTier


class IntentClassificationResult(BaseModel):
    """Result of intent analysis on user input."""

    intent: TaskIntent
    confidence: float = Field(ge=0.0, le=1.0)
    reasoning: str


class VerificationResult(BaseModel):
    """Independent outcome verification result for a step or task."""

    verified: bool
    outcome: TaskOutcome
    reason: str
    details: dict[str, Any] = Field(default_factory=dict)


class AuditEventType(StrEnum):
    """Types of audit events emitted during task lifecycle."""

    TASK_CREATED = "TASK_CREATED"
    PLAN_GENERATED = "PLAN_GENERATED"
    STEP_STARTED = "STEP_STARTED"
    POLICY_EVALUATED = "POLICY_EVALUATED"
    TOOL_EXECUTED = "TOOL_EXECUTED"
    OUTCOME_VERIFIED = "OUTCOME_VERIFIED"
    TASK_COMPLETED = "TASK_COMPLETED"
    TASK_FAILED = "TASK_FAILED"
    TASK_CANCELLED = "TASK_CANCELLED"


class ActionStep(BaseModel):
    """A discrete, verifiable action in a task plan."""

    step_index: int = Field(ge=1, description="1-based step order")
    tool_name: str = Field(description="Exact tool identifier to execute")
    parameters: dict[str, Any] = Field(default_factory=dict, description="Validated parameters")
    expected_outcome: str = Field(description="Description of verified outcome")
    status: str = Field(
        default="pending", description="Status: pending, running, completed, failed, cancelled"
    )
    result: Any | None = Field(default=None, description="Actual output returned by tool")
    error: str | None = Field(default=None, description="Error message if execution failed")
    verified: bool = Field(
        default=False, description="Whether outcome was confirmed by independent verifier"
    )


class TaskPlan(BaseModel):
    """Structured execution plan generated by the planner and validated by policy."""

    goal: str = Field(min_length=1, description="Original user goal")
    intent: TaskIntent = Field(description="Classified semantic intent")
    steps: list[ActionStep] = Field(default_factory=list, description="Ordered action steps")
    requires_approval: bool = Field(default=False, description="Whether approval gate is required")
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))


class Task(BaseModel):
    """Full persistent task representation."""

    task_id: str = Field(description="Unique persistent identifier (task_<timestamp>_<hex>)")
    goal: str = Field(description="User objective")
    intent_type: TaskIntent = Field(default=TaskIntent.TASK_EXECUTION)
    state: TaskState = Field(default=TaskState.CREATED)
    outcome: TaskOutcome = Field(default=TaskOutcome.UNKNOWN)
    plan: TaskPlan | None = Field(default=None)
    current_step_index: int = Field(default=0)
    error_message: str | None = Field(default=None)
    result_summary: str | None = Field(
        default=None, description="Grounded summary of completed task output"
    )
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    updated_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
